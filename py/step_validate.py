"""Step: validate (offline). The SHACL gate over the bundle, with a self-test.

    dist/validation_report.md   what the rules found, per rule, with a few focus nodes

Order: (1) the shapes (metadata/shapes.ttl) are run on tests/shacl/good.ttl, which must give no violation and no warning,
and on tests/shacl/bad.ttl, which must give every rule of tests/shacl/expected.json with that severity: a gate that cannot
fail passes everything. (2) Only then is the bundle judged.

Severity follows the modal verb of the rule: MUST is a violation and stops the build, SHOULD is a warning and stops it with
--strict, MAY is information and is only reported. Every rule has a code (R01 ...) in its message.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from registry_utils import DIST, METADATA, ROOT, ensure_dirs  # noqa: E402

SHAPES = METADATA / "shapes.ttl"
TESTS = ROOT / "tests" / "shacl"
BUNDLE = DIST / "beaverbridge-registry.ttl"
RE_CODE = re.compile(r"^(R[0-9]+):")
ORDER = {"Violation": 0, "Warning": 1, "Info": 2}


def run(data_path: Path, shapes):
    """Results of one validation: {code: {"severity", "message", "nodes": set}}."""
    from pyshacl import validate
    from rdflib import Graph
    from rdflib.namespace import SH

    data = Graph()
    data.parse(data_path, format="turtle")
    conforms, report, _ = validate(data, shacl_graph=shapes, inference="none", advanced=True)
    if not hasattr(report, "subjects"):  # pyshacl returns a ValidationFailure when the shapes themselves are broken
        raise RuntimeError(f"the shapes could not be used: {report}")
    found = defaultdict(lambda: {"severity": "", "message": "", "nodes": set(), "n": 0})
    for res in report.subjects(SH.resultSeverity, None):
        msg = str(report.value(res, SH.resultMessage))
        m = RE_CODE.match(msg)
        code = m.group(1) if m else "R??"
        f = found[code]
        f["severity"] = str(report.value(res, SH.resultSeverity)).rsplit("#", 1)[-1]
        f["message"] = re.sub(r"\{\?[a-z]+\}", "…", msg.split(";")[0]) if m else msg
        f["nodes"].add(str(report.value(res, SH.focusNode)))
        f["n"] += 1
    return len(data), found


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--strict", action="store_true")
    args = ap.parse_args()
    ensure_dirs()

    try:
        import pyshacl  # noqa: F401
        from rdflib import Graph
    except ImportError as exc:
        print(f"validate: {exc}. Install it with  pip install -r requirements.txt")
        return 1

    shapes = Graph()
    shapes.parse(SHAPES, format="turtle")

    # --- 1. the self-test
    expected = json.loads((TESTS / "expected.json").read_text(encoding="utf-8"))
    try:
        _, good = run(TESTS / "good.ttl", shapes)
        _, bad = run(TESTS / "bad.ttl", shapes)
    except RuntimeError as exc:
        print(f"validate: self-test failed: {exc}")
        return 1
    problems = [f"good.ttl: {c} ({v['severity']}) was reported: {sorted(v['nodes'])[0]}"
                for c, v in sorted(good.items()) if v["severity"] in ("Violation", "Warning")]
    for code, severity in sorted(expected.items()):
        if code not in bad:
            problems.append(f"bad.ttl: {code} was not reported; the gate cannot see this fault")
        elif bad[code]["severity"] != severity:
            problems.append(f"bad.ttl: {code} has severity {bad[code]['severity']}, expected {severity}")
    for code in sorted(set(bad) - set(expected)):
        problems.append(f"bad.ttl: {code} is reported but not listed in expected.json")
    if problems:
        print("validate: SELF-TEST FAILED, the gate is not to be trusted:")
        for p in problems:
            print(f"  {p}")
        return 1
    print(f"validate: self-test ok ({len(expected)} rules fail on bad.ttl, nothing on good.ttl)")

    # --- 2. the bundle
    if not BUNDLE.exists():
        print("validate: no bundle, nothing judged")
        return 1 if args.strict else 0
    n, found = run(BUNDLE, shapes)
    counts = {s: sum(v["n"] for v in found.values() if v["severity"] == s) for s in ORDER}

    L = ["# Validation report", "", "Generated by `py/step_validate.py` from `metadata/shapes.ttl`. Do not edit.", "",
         f"Bundle `dist/beaverbridge-registry.ttl`, {n} triples. Self-test: {len(expected)} rules fail on `tests/shacl/bad.ttl`, "
         "nothing on `tests/shacl/good.ttl`.", "",
         f"**{counts['Violation']}** violations, **{counts['Warning']}** warnings, **{counts['Info']}** notes.", ""]
    if found:
        L += ["| Code | Severity | Results | Rule | Examples |", "|---|---|---|---|---|"]
        for code, v in sorted(found.items(), key=lambda kv: (ORDER[kv[1]["severity"]], kv[0])):
            ex = ", ".join(f"`{x.rsplit('/', 1)[-1]}`" for x in sorted(v["nodes"])[:4])
            L.append(f"| {code} | {v['severity']} | {v['n']} | {v['message'].split(': ', 1)[-1]} | {ex} |")
        L.append("")
    (DIST / "validation_report.md").write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")

    for code, v in sorted(found.items(), key=lambda kv: (ORDER[kv[1]["severity"]], kv[0])):
        if v["severity"] != "Info":
            print(f"  {v['severity'].upper()} {code} x{v['n']}: {v['message']}")
    print(f"validate: {counts['Violation']} violation(s), {counts['Warning']} warning(s), {counts['Info']} note(s)")
    if counts["Violation"]:
        return 1
    return 1 if (counts["Warning"] and args.strict) else 0


if __name__ == "__main__":
    sys.exit(main())
